// Run on macOS with the built-in Samantha voice and ffmpeg installed.
import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, rename, rm, stat, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parts, slots, readPart, partReading } from '../js/catalog.js'

const workspace = await mkdtemp(join(tmpdir(), 'bolt-part-reader-'))
const root = new URL('../', import.meta.url)
// At 24 kHz and 48 kb/s each MPEG-2 Layer III frame has 144 bytes and 576 samples.
// Independent streams with the same header concatenate into one playable track.
// Disabling the bit reservoir lets Web Audio decode any indexed part on its own.
const frameBytes = 144
const bytesPerSecond = 6000
async function encode(text) {
  const input = join(workspace, 'voice.aiff')
  const encoded = join(workspace, 'voice.mp3')
  execFileSync('say', ['-v', 'Samantha', '-r', '164', '-o', input, text])
  if ((await stat(input)).size < 10000)
    throw Error('Speech engine returned no recording for ' + text)
  execFileSync('ffmpeg', [
    '-nostdin',
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-i',
    input,
    '-map_metadata',
    '-1',
    '-af',
    'highpass=f=72,equalizer=f=2200:t=q:w=0.9:g=1,acompressor=threshold=0.12:ratio=1.7:attack=10:release=70,loudnorm=I=-19:TP=-2.2:LRA=6,aresample=24000,adelay=30,apad=pad_dur=0.07',
    '-ar',
    '24000',
    '-ac',
    '1',
    '-c:a',
    'libmp3lame',
    '-b:a',
    '48k',
    '-reservoir',
    '0',
    '-write_xing',
    '0',
    '-id3v2_version',
    '0',
    encoded
  ])
  const bytes = await readFile(encoded)
  if (bytes.length % frameBytes !== 0) throw Error('Unexpected MP3 frame length for ' + text)
  for (let p = 0; p < bytes.length; p += frameBytes)
    if (bytes[p] !== 0xff || (bytes[p + 1] & 0xfe) !== 0xf2)
      throw Error('Unexpected MP3 header for ' + text)
  return bytes
}
const pending = []
async function writeAsset(name, data) {
  const file = fileURLToPath(new URL(name, root))
  const staging = join(workspace, String(pending.length))
  await writeFile(staging, data)
  pending.push([staging, file])
}

const readerCues = {}, comparisons = {}
let count = 0
try {
  const baseline = []
  let baseBytes = 0
  for (const { id } of slots) {
    const file = 'shop-' + id + '-swaps.mp3'
    const lines = [], audio = [], sentences = new Map()
    let offset = 0
    async function recordSentence(text) {
      if (sentences.has(text)) return sentences.get(text)
      const bytes = await encode(text)
      const slice = [offset, bytes.length]
      offset += bytes.length
      sentences.set(text, slice)
      audio.push(bytes)
      return slice
    }
    readerCues[id] = []
    for (const [index] of parts[id].entries()) {
      if (!process.argv.includes('--comparisons')) {
        const text = readPart(id, index)
        const bytes = await encode(text)
        readerCues[id].push({ start: baseBytes / bytesPerSecond, duration: bytes.length / bytesPerSecond, text })
        baseBytes += bytes.length
        baseline.push(bytes)
      }
      const byFitted = []
      for (const [fitted] of parts[id].entries()) {
        if (fitted === index) { byFitted.push(null); continue }
        const words = partReading(id, index, fitted), byteRanges = []
        for (const sentence of words) byteRanges.push(await recordSentence(sentence))
        const duration = byteRanges.reduce((sum, [,length]) => sum + length, 0) / bytesPerSecond
        byFitted.push({ byteRanges, duration, text: words.join(' ') })
        count++
      }
      lines.push(byFitted)
    }
    comparisons[id] = { file, lines }
    await writeAsset('art/' + file, Buffer.concat(audio))
  }
  const header = '// Generated by tools/bake-part-reader.mjs. Times are seconds.\n'
  if (baseline.length) {
    await writeAsset('art/shop-reader.mp3', Buffer.concat(baseline))
    await writeAsset('js/part-reader-cues.js', header + 'export const readerBytesPerSecond = ' + bytesPerSecond +
      '\nexport const readerCues = ' + JSON.stringify(readerCues, null, 2) + '\n')
  }
  await writeAsset('js/shop-comparisons.js', header + 'export const shopComparisons = ' + JSON.stringify(comparisons, null, 2) + '\n')
  for (const [staging, file] of pending) await rename(staging, file)
  console.log(baseline.length + ' part introductions and ' + count + ' comparison readings.')
} finally {
  await rm(workspace, { recursive: true, force: true })
}
