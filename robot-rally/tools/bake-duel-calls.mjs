// Run on macOS with the built-in Daniel and Samantha voices and ffmpeg.
// Each matchup is one small track. Only the current pair needs decoding.
import { execFileSync } from 'node:child_process'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { frames, rounds } from '../js/catalog.js'
import { duelKey, duelKinds, duelWords } from '../js/duel-calls.js'

const output = process.argv[2] || fileURLToPath(new URL('../', import.meta.url))
const temp = await mkdtemp(join(tmpdir(), 'bolt-desk-'))
const rate = 32000
const pad = Buffer.alloc(2 * 3072)
const data = {}
function voiceBuffer(source) {
  const raw = execFileSync('ffmpeg', [
    '-nostdin',
    '-v',
    'error',
    '-i',
    source,
    '-ar',
    String(rate),
    '-ac',
    '1',
    '-af',
    'highpass=f=74,equalizer=f=2550:t=q:w=0.92:g=1.25,acompressor=threshold=0.12:ratio=1.85:attack=12:release=85',
    '-f',
    's16le',
    '-'
  ])
  const samples = new Int16Array(raw.buffer, raw.byteOffset, raw.length / 2)
  let first = samples.findIndex((v) => Math.abs(v) > 50),
    last = samples.findLastIndex((v) => Math.abs(v) > 50)
  if (first < 0 || last - first < rate * 0.35) throw Error('Silent clip ' + source)
  first = Math.max(0, first - 640)
  last = Math.min(samples.length, last + 1500)
  const result = Buffer.from(raw.subarray(first * 2, last * 2))
  let peak = 1,
    sum = 0
  for (let i = 0; i < result.length; i += 2) {
    const v = result.readInt16LE(i)
    peak = Math.max(peak, Math.abs(v))
    sum += v * v
  }
  const gain = Math.min(28000 / peak, 3800 / Math.sqrt(sum / (result.length / 2)))
  for (let i = 0; i < result.length; i += 2) result.writeInt16LE(Math.round(result.readInt16LE(i) * gain), i)
  return result
}
try {
  const art = join(output, 'art/broadcast/exchanges')
  await mkdir(art, { recursive: true })
  for (const [r, { rival }] of rounds.entries()) {
    for (const [h, home] of [...frames.map((f) => f.name), 'yourBot'].entries()) {
      const key = duelKey(home, rival)
      const chunks = [pad]
      let length = pad.length / 2
      const clips = []
      for (const [k, kind] of duelKinds.entries())
        for (const side of [0, 1]) {
          const variant = (h + k + side + r) % 2
          const text = duelWords(kind, side, [home === 'yourBot' ? 'your bot' : home, rival], variant)
          const analyst = kind.startsWith('reason')
          const source = join(temp, 'voice.aiff')
          execFileSync('say', [
            '-v',
            analyst ? 'Samantha' : 'Daniel',
            '-r',
            String((analyst ? 178 : 185) + ((h + r) % 4)),
            '-o',
            source,
            text
          ])
          const clip = voiceBuffer(source)
          clips.push([length, clip.length / 2, variant])
          length += (clip.length + pad.length) / 2
          chunks.push(clip, pad)
        }
      const target = join(art, key + '.m4a')
      execFileSync(
        'ffmpeg',
        [
          '-nostdin',
          '-y',
          '-v',
          'error',
          '-f',
          's16le',
          '-ar',
          String(rate),
          '-ac',
          '1',
          '-i',
          '-',
          '-c:a',
          'aac',
          '-b:a',
          '48k',
          '-brand',
          'mp42',
          '-movflags',
          '+faststart',
          target
        ],
        { input: Buffer.concat(chunks) }
      )
      if ((await readFile(target)).length < 10000) throw Error('Empty commentary track ' + key)
      data[key] = clips
    }
    console.log('Recorded the matchups against', rival)
  }
  const manifest = join(output, 'js/duel-recordings.js')
  await mkdir(dirname(manifest), { recursive: true })
  const sources = Object.keys(data).map(
    (key) =>
      '  ' +
      JSON.stringify(key) +
      ': new URL(' +
      JSON.stringify('../art/broadcast/exchanges/' + key + '.m4a') +
      ', import.meta.url).href'
  )
  const clips = Object.entries(data).map(
    ([key, cues]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(cues)
  )
  await writeFile(
    manifest,
    '// Generated by tools/bake-duel-calls.mjs. Offsets and lengths are PCM samples.\nexport const duelRate = ' +
      rate +
      '\nexport const duelTracks = {\n' +
      sources.join(',\n') +
      '\n}\nexport const duelClips = {\n' +
      clips.join(',\n') +
      '\n}\n'
  )
} finally {
  await rm(temp, { recursive: true, force: true })
}
