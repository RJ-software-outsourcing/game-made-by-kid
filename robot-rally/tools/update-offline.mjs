// Run after changing shipped files. No bundler is required for the game itself.
import { createHash } from 'node:crypto'
import { posix } from 'node:path'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { buildBracket } from '../js/bracket.js'
const base = new URL('../', import.meta.url)
async function publish(path, content) {
  const target = new URL(path, base)
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')) !== content)
      throw Error('Run node robot-rally/tools/update-offline.mjs to refresh ' + path)
  } else {
    await writeFile(target, content)
  }
}

// Rival qualifiers have fixed seeds and budgets. The tablet can display the
// draw immediately without running eleven other bouts on a child's first tap.
const draw = buildBracket().map((round) => round.map(({ left, right, winner }) => ({ left, right, winner })))
await publish('js/tournament-draw.js',
  '// Generated from the seeded rival qualifiers by tools/update-offline.mjs.\nexport const draw = [\n' +
  draw.map((round) => '  [\n' + round.map((pair) => '    ' + JSON.stringify(pair)).join(',\n') + '\n  ]').join(',\n') +
  '\n]\n')
// Follow the same module graph as the browser. Old prototypes and test-only
// utilities should never slow down a child's first offline installation.
const entry = ['index.html', 'style.css', 'equipment.css', 'garage.css', 'manifest.webmanifest', 'js/game.js']
const sources = new Map()
async function visit(path) {
  if (sources.has(path)) return
  const source = await readFile(new URL(path, base), 'utf8')
  sources.set(path, source)
  if (!path.endsWith('.js')) return
  for (const match of source.matchAll(/(?:from\s*|import\s*\(?\s*)['"](\.\.?\/[^'"]+\.js)['"]/g)) {
    const child = posix.normalize(posix.join(posix.dirname(path), match[1]))
    if (child.startsWith('../')) throw Error('Offline dependency outside game: ' + child)
    await visit(child)
  }
}
for (const path of entry) await visit(path)
const files = [...sources.keys()]
async function collectArt(dir) {
  for (const entry of await readdir(new URL(dir, base), { withFileTypes: true })) {
    const path = dir + entry.name
    if (entry.isDirectory()) await collectArt(path + '/')
    else if ([...sources.values()].some((source) => source.includes(entry.name))) files.push(path)
  }
}
await collectArt('art/')
files.sort()
const hash = createHash('sha256')
const assets = {}
for (const path of [...files, 'sw.js']) {
  const bytes = await readFile(new URL(path, base))
  hash.update(path + '\0')
  hash.update(bytes)
  if (path !== 'sw.js') assets[path] = createHash('sha256').update(bytes).digest('base64')
}
const version = hash.digest('hex').slice(0, 14)
const output =
  '// Generated by tools/update-offline.mjs\nconst RALLY_OFFLINE = ' +
  JSON.stringify({ version, assets }, null, 2) +
  '\n'
await publish('offline-assets.js', output)
